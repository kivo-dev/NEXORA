"""Domain model for financial reports in the Nexora platform.

This module defines the core domain abstraction for a final financial
report generated by the Nexora platform. It belongs to the Domain Layer
and is intentionally free of generation logic, persistence concerns,
and provider-specific details.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field, field_validator

from app.models.analysis import Analysis
from app.models.wallet import Wallet


class ReportType(StrEnum):
    """Canonical classification of financial report types."""

    SUMMARY = "summary"
    """High-level executive summary across all dimensions."""

    PORTFOLIO = "portfolio"
    """Detailed portfolio composition and allocation report."""

    RISK = "risk"
    """Risk exposure and vulnerability assessment report."""

    PERFORMANCE = "performance"
    """Historical performance and benchmarking report."""

    TAX = "tax"
    """Tax-relevant transaction and gain/loss report."""

    CUSTOM = "custom"
    """User-defined or ad-hoc custom report."""

    UNKNOWN = "unknown"
    """Unclassified or generic report type."""


class Report(BaseModel):
    """Immutable domain representation of a generated financial report.

    A ``Report`` aggregates one or more analytical evaluations into a
    cohesive, final deliverable for a specific wallet. It captures
    metadata, classification, and the underlying analyses without
    embedding generation logic, AI provider details, or presentation
    concerns.

    Attributes:
        report_id: Unique identifier for the report instance.
        wallet: Wallet that is the subject of the report.
        report_type: Category of the generated report.
        title: Human-readable title of the report.
        summary: Executive summary of the report contents.
        analyses: Collection of underlying analysis instances.
        generated_at: UTC datetime when the report was produced.
    """

    model_config = ConfigDict(
        frozen=True,
        strict=True,
        populate_by_name=True,
    )

    report_id: str = Field(
        ...,
        min_length=1,
        title="Report ID",
        description="Unique identifier for the report instance.",
    )
    wallet: Wallet = Field(
        ...,
        title="Wallet",
        description="Wallet that is the subject of the report.",
    )
    report_type: ReportType = Field(
        ...,
        title="Report Type",
        description="Category of the generated report.",
    )
    title: str = Field(
        ...,
        min_length=1,
        title="Title",
        description="Human-readable title of the report.",
    )
    summary: str = Field(
        ...,
        min_length=1,
        title="Summary",
        description="Executive summary of the report contents.",
    )
    analyses: list[Analysis] = Field(
        default_factory=list,
        title="Analyses",
        description="Collection of underlying analysis instances.",
    )
    generated_at: datetime = Field(
        ...,
        title="Generated At",
        description="UTC datetime when the report was generated.",
    )

    @field_validator("report_id", "title", "summary", mode="before")
    @classmethod
    def _validate_non_empty_string(cls, value: object) -> str:
        """Ensure required text fields are non-empty strings after stripping."""
        if not isinstance(value, str):
            raise TypeError("Field must be a string")
        stripped = value.strip()
        if not stripped:
            raise ValueError("Field must not be empty")
        return stripped

    @field_validator("report_type", mode="before")
    @classmethod
    def _normalize_report_type(cls, value: object) -> ReportType:
        """Normalize raw input to a canonical ReportType member."""
        if isinstance(value, ReportType):
            return value
        if isinstance(value, str):
            normalized = value.strip().lower()
            try:
                return ReportType(normalized)
            except ValueError:
                return ReportType.UNKNOWN
        raise TypeError("Report type must be a string or ReportType")

    @field_validator("analyses", mode="before")
    @classmethod
    def _validate_analyses(cls, value: object) -> list[Analysis]:
        """Ensure analyses is a list of Analysis instances."""
        if not isinstance(value, list):
            raise TypeError("Analyses must be a list")
        for item in value:
            if not isinstance(item, Analysis):
                raise TypeError("Each analysis must be an Analysis instance")
        return value


__all__ = [
    "ReportType",
    "Report",
]
